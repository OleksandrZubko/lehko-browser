import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { convert } from './lib/abp-to-dnr.mjs';
const cache = new URL('../artifacts/filter-lists/', import.meta.url);
const out = new URL('../extension/rules/', import.meta.url);
const LIMIT = 30000;
const refresh = process.argv.includes('--refresh');
const lists = [
  { id: 'ads', name: 'EasyList', file: 'easylist.txt', url: 'https://easylist.to/easylist/easylist.txt' },
  { id: 'privacy', name: 'EasyPrivacy', file: 'easyprivacy.txt', url: 'https://easylist.to/easylist/easyprivacy.txt' }
];

async function load(list) {
  const path = new URL(list.file, cache);
  const cached = await stat(path).then(() => true, () => false);
  if (refresh || !cached) {
    const res = await fetch(list.url);
    if (!res.ok) throw new Error(`${list.url}: HTTP ${res.status}`);
    const text = await res.text();
    if (!/^\[Adblock/i.test(text) || text.length < 10000) throw new Error(`${list.url}: unexpected content (${text.length} bytes)`);
    await writeFile(path, text);
    console.log(`downloaded ${list.url}`);
  }
  const [text, info] = await Promise.all([readFile(path, 'utf8'), stat(path)]);
  return { text, fetched: info.mtime.toISOString().slice(0, 10), version: /^! Version:\s*(.+)$/m.exec(text)?.[1] ?? 'unknown' };
}

async function main() {
  await mkdir(cache, { recursive: true });
  await mkdir(out, { recursive: true });
  const built = [];
  for (const list of lists) {
    const src = await load(list);
    const { rules, stats } = convert(src.text);
    console.log(`${list.name}: ${stats.lines} lines, ${stats.converted} filters converted -> ${rules.length} rules (${stats.domainFilters} domain filters merged), ${stats.duplicates} duplicates`);
    console.log(`  skipped ${stats.skippedTotal}: ${JSON.stringify(stats.skipped)}`);
    console.log(`  unsupported options: ${JSON.stringify(stats.unsupported)}`);
    if (rules.length > LIMIT) throw new Error(`${list.name}: ${rules.length} rules exceeds the ${LIMIT} static rule limit`);
    built.push({ list, src, rules });
  }
  for (const { list, rules } of built) await writeFile(new URL(`${list.id}.json`, out), JSON.stringify(rules));
  const date = built.map(b => `  - ${b.list.name} (${b.list.url}), version ${b.src.version}, fetched ${b.src.fetched}`).join('\n');
  await writeFile(new URL('LICENSE.txt', out), `The files in this directory (ads.json, privacy.json) are Chrome declarativeNetRequest
rulesets generated by scripts/build-rules.mjs from these filter lists:

${date}

EasyList and EasyPrivacy are copyright their respective authors and are dual licensed
under the GNU General Public License v3 and the Creative Commons Attribution-ShareAlike 3.0
Unported license (CC BY-SA 3.0). See https://easylist.to/pages/licence.html

The rulesets are a format conversion (a subset of the filter syntax, with domain-only
filters merged) and remain available under those same terms.
`);
  const total = built.reduce((n, b) => n + b.rules.length, 0);
  for (const b of built) console.log(`rules/${b.list.id}.json: ${b.rules.length} rules`);
  console.log(`total enabled rules if both on: ${total}${total > LIMIT ? ` (over ${LIMIT}: only guaranteed minimum is ${LIMIT} per extension)` : ''}`);
}
main().catch(e => { console.error(`build-rules failed: ${e.message}`); process.exit(1); });
